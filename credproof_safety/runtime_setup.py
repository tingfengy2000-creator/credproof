"""Trusted Linux runtime preparation and byte-level reuse checks (contract R3)."""
from __future__ import annotations

import hashlib
import json
import os
from pathlib import Path
import platform
import subprocess
import sys

SCHEMA = 'credproof.linux-runtime/v1'
LOCK = Path(__file__).with_name('requirements-lock.txt')


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def supported():
    if sys.platform != 'linux' or platform.machine() != 'x86_64' or os.getuid() == 0:
        raise ValueError('Requires non-root Ubuntu 24.04 x86_64 / system Python 3.12')
    info = platform.freedesktop_os_release()
    if info.get('ID') != 'ubuntu' or info.get('VERSION_ID') != '24.04' or sys.version_info[:2] != (3, 12):
        raise ValueError('Unsupported distribution or Python; use Ubuntu 24.04 / Python 3.12')
    system = subprocess.run(['/usr/bin/python3', '-I', '-c', 'import sys;print(sys.version_info[:2])'],
                            capture_output=True, text=True, check=True, timeout=10)
    if system.stdout.strip() != '(3, 12)':
        raise ValueError('System Python must be 3.12')


def safe_root(value):
    path = Path(value).expanduser().absolute()
    if path == Path('/') or any(p.is_symlink() for p in (path, *path.parents)):
        raise ValueError('Runtime root must be a dedicated non-linked directory')
    return path


def inventory(root):
    """No links, special files or host-tree aliases; omit only generated bytecode."""
    root = Path(root)
    if any(p.is_symlink() for p in (root, *root.parents)) or root.resolve() == Path('/') or not root.is_dir():
        raise ValueError('Invalid dedicated snapshot')
    result = {}
    for p in sorted(root.rglob('*')):
        relative = p.relative_to(root).as_posix()
        if '__pycache__' in p.relative_to(root).parts or p.suffix == '.pyc':
            continue
        if p.is_symlink():
            raise ValueError('Snapshot contains a symbolic link')
        if p.is_file():
            result[relative] = {'sha256': sha(p), 'bytes': p.stat().st_size,
                                'mode': p.stat().st_mode & 0o777}
        elif p.is_dir():
            result[relative] = {'directory': True, 'mode': p.stat().st_mode & 0o777}
        else:
            raise ValueError('Snapshot contains a special file')
    if not result:
        raise ValueError('Empty snapshot')
    return result


def write_json(path, value):
    Path(path).write_text(json.dumps(value, sort_keys=True, indent=2) + '\n', encoding='utf8')


def verify_runtime(root):
    root = safe_root(root)
    receipt = json.loads((root / 'runtime-receipt.json').read_text('utf8'))
    manifest = json.loads((root / 'rootfs-manifest.json').read_text('utf8'))
    if receipt.get('schema') != SCHEMA or manifest.get('schema') != SCHEMA:
        raise ValueError('Runtime metadata schema mismatch; use a new runtime-root')
    if receipt['lock_sha256'] != sha(LOCK):
        raise ValueError('Dependency lock changed; use a new runtime-root')
    if receipt['manifest_sha256'] != sha(root / 'rootfs-manifest.json'):
        raise ValueError('Rootfs manifest changed')
    if manifest.get('preparer_sha256') != sha(__file__):
        raise ValueError('Preparation implementation changed; use a new runtime-root')
    if manifest['files'] != inventory(root / 'isolation/rootfs'):
        raise ValueError('Rootfs bytes or modes changed')
    if receipt['site_files'] != inventory(root / 'venv/lib/python3.12/site-packages'):
        raise ValueError('Installed dependencies changed')
    if receipt['bwrap_sha256'] != sha(root / 'isolation/tools/usr/bin/bwrap'):
        raise ValueError('Bubblewrap changed')
    if (root / 'isolation/tools/usr/bin/bwrap').stat().st_mode & 0o6000:
        raise ValueError('Setuid/setgid bubblewrap is forbidden')
    from agent_pilot.sandbox_runner import PACKAGE_SHA256
    if receipt['package_sha256'] != PACKAGE_SHA256:
        raise ValueError('Bubblewrap package configuration changed')
    return receipt


def setup(root):
    supported()
    root = safe_root(root)
    if root.exists() and any(root.iterdir()):
        verify_runtime(root)  # Never modify previous preparation/probe receipts.
        return root, 'REUSED'
    root.mkdir(parents=True, exist_ok=True)
    # prepare() remains unchanged for old model runtimes; only redirect its
    # trusted BASE for this fresh preparation, then restore the module state.
    from agent_pilot import sandbox_runner
    previous = sandbox_runner.BASE
    try:
        sandbox_runner.BASE = root / 'isolation'
        preparation = sandbox_runner.prepare('linux-runtime-v1')
    finally:
        sandbox_runner.BASE = previous
    subprocess.run(['/usr/bin/python3', '-m', 'venv', str(root / 'venv')], check=True, timeout=90)
    subprocess.run([str(root / 'venv/bin/python'), '-m', 'pip', 'install', '--disable-pip-version-check',
                    '--only-binary=:all:', '--require-hashes', '-r', str(LOCK)], check=True, timeout=180)
    packages = subprocess.run(['dpkg-query', '-W', '-f=${Package}=${Version}\n',
                               'python3', 'libpython3.12-stdlib', 'libc6', 'libseccomp2'],
                              capture_output=True, text=True, check=True, timeout=10)
    manifest = {'schema': SCHEMA, 'preparer_sha256': sha(__file__),
                'sources': packages.stdout.splitlines(), 'files': inventory(root / 'isolation/rootfs')}
    write_json(root / 'rootfs-manifest.json', manifest)
    write_json(root / 'runtime-receipt.json', {
        'schema': SCHEMA, 'lock_sha256': sha(LOCK), 'manifest_sha256': sha(root / 'rootfs-manifest.json'),
        'package_sha256': sandbox_runner.PACKAGE_SHA256, 'bwrap_sha256': preparation['bwrap_sha256'],
        'python': platform.python_version(), 'site_files': inventory(root / 'venv/lib/python3.12/site-packages')})
    write_json(root / 'runtime.json', {'runtime_root': str(root)})
    verify_runtime(root)
    return root, 'CREATED'


def main(argv=None):
    import argparse
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--runtime-root', default='~/credproof-agent-runtime')
    args = p.parse_args(argv)
    try:
        root, status = setup(args.runtime_root)
        from .doctor import doctor
        report = doctor(root)
        print(json.dumps({'preparation': status, **report}, sort_keys=True))
        return 0 if report['ready'] else 4
    except (OSError, ValueError, KeyError, subprocess.SubprocessError) as exc:
        print(json.dumps({'ready': False, 'error_type': type(exc).__name__,
                          'hints': ['Preparation failed; preserve this directory and use a new versioned runtime-root.'],
                          'detail': str(exc)}), file=sys.stderr)
        return 4


if __name__ == '__main__':
    raise SystemExit(main())
