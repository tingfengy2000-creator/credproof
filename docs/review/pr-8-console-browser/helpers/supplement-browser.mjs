import {createRequire} from 'node:module';
import {mkdirSync,writeFileSync} from 'node:fs';
import {join,resolve} from 'node:path';
const require=createRequire(join(process.cwd(),'noop.js'));
const {chromium}=require('playwright');
const out=resolve(process.argv[2]||'supplement'); mkdirSync(out,{recursive:true});
const browser=await chromium.launch({channel:'msedge'});
const page=await browser.newPage({viewport:{width:1440,height:900}});
const results={browser:browser.version(),writes:[],errors:[]};
page.on('request',r=>{if(r.method()!=='GET')results.writes.push(r.method()+' '+r.url());});
page.on('pageerror',e=>results.errors.push(e.message));
await page.goto('http://127.0.0.1:8768/#overview',{waitUntil:'networkidle'});
results.matrix=await page.locator('#matrix').evaluate(m=>({columns:m.querySelectorAll('.cell-spacer').length,rows:m.querySelectorAll('.cells').length-1}));
results.targets=await page.locator('#target-table tbody tr').count();
await page.goto('http://127.0.0.1:8768/#patch/b07-webhook-relay__qwen3-coder-30b__s1__r0',{waitUntil:'networkidle'});
await page.getByText('与漏洞原版没有任何差异。',{exact:true}).waitFor();
const patch=await page.locator('#patch-detail').innerText();
results.b07={fail:patch.includes('不通过'),same_bytes:patch.includes('与漏洞原版逐字节相同'),empty_diff:patch.includes('与漏洞原版没有任何差异。')};
await page.screenshot({path:join(out,'b07-readonly.png'),fullPage:true});
await page.goto('http://127.0.0.1:8768/#human-review',{waitUntil:'networkidle'});
await page.locator('#review-states').waitFor({state:'visible'});
results.review_state=await page.locator('#review-states').innerText();
await page.screenshot({path:join(out,'human-review.png'),fullPage:true});
await page.goto('http://127.0.0.1:8768/#workbench',{waitUntil:'networkidle'});
results.start={enabled:await page.locator('#start').isEnabled(),title:await page.locator('#start').getAttribute('title')};
await page.screenshot({path:join(out,'workbench.png'),fullPage:true});
results.pass=results.matrix.columns===67&&results.matrix.rows===5&&results.targets===8&&Object.values(results.b07).every(Boolean)&&results.writes.length===0&&results.errors.length===0;
writeFileSync(join(out,'summary.json'),JSON.stringify(results,null,2)+'\n');
await browser.close();console.log(JSON.stringify(results));process.exit(results.pass?0:1);
